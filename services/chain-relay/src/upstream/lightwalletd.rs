/*
  upstream/lightwalletd.rs — Tonic gRPC client for lightwalletd.

  This module wraps the subset of the lightwalletd gRPC API that the relay
  needs, applying per-call timeouts and retries.

  Privacy guarantees
  ──────────────────
  • Only PUBLIC data is fetched: compact block ranges (for trial decryption
    by the WASM worker in the browser) and explicit transaction bytes
    (when the user approves a memo fetch).
  • The relay NEVER receives a viewing key, address, label, amount, decrypted
    note, passphrase or any other private data.
  • Transaction IDs forwarded to this client have been validated to be 64-char
    hex by the validation module before reaching here.
  • Transaction-ID query paths are REDACTED from routine application logs
    (see `fetch_transaction`).

  Compact block format
  ────────────────────
  lightwalletd exposes `GetBlockRange(BlockRange)` returning a stream of
  `CompactBlock` protobuf messages. We serialise each block to protobuf bytes
  and concatenate them, length-prefixed, into a single binary blob.

  The browser-side WASM worker (Phase 5/8) knows how to decode this format.
  We return raw bytes rather than re-interpreting the data server-side.

  Stale tip detection
  ───────────────────
  `get_latest_block_height` returns the tip as reported by the upstream.
  If the tip has not advanced within a configurable staleness window the
  route handler returns `SourceStale` rather than a block response.
*/

use std::time::Duration;

use tokio::time::timeout;
use tonic::transport::{Certificate, Channel, ClientTlsConfig};

use crate::config::LimitsConfig;
use crate::error::RelayError;
use crate::validation::validate_response_size;

// ---------------------------------------------------------------------------
// lightwalletd protobuf types (manually defined subset)
//
// In a fully-wired build these would be generated by `prost-build` from the
// lightwalletd .proto files (https://github.com/zcash/lightwalletd/blob/master/walletrpc/service.proto).
// They are defined here as minimal hand-written structs so the relay compiles
// without a build.rs / proto codegen step that is not yet authorised to run.
// ---------------------------------------------------------------------------

pub mod proto {
    use prost::Message;

    /// Minimal BlockID for GetBlock / GetLatestBlock.
    #[derive(Clone, PartialEq, Message)]
    pub struct BlockId {
        #[prost(uint64, tag = "1")]
        pub height: u64,
        #[prost(bytes, tag = "2")]
        pub hash: Vec<u8>,
    }

    /// Range of block heights for GetBlockRange.
    #[derive(Clone, PartialEq, Message)]
    pub struct BlockRange {
        #[prost(message, optional, tag = "1")]
        pub start: Option<BlockId>,
        #[prost(message, optional, tag = "2")]
        pub end: Option<BlockId>,
    }

    /// Compact block returned by GetBlockRange.
    #[derive(Clone, PartialEq, Message)]
    pub struct CompactBlock {
        #[prost(uint32, tag = "1")]
        pub proto_version: u32,
        #[prost(uint64, tag = "2")]
        pub height: u64,
        #[prost(bytes, tag = "3")]
        pub hash: Vec<u8>,
        #[prost(bytes, tag = "4")]
        pub prev_hash: Vec<u8>,
        #[prost(uint32, tag = "5")]
        pub time: u32,
        /// Raw compact transaction data.
        #[prost(bytes, tag = "6")]
        pub header: Vec<u8>,
        #[prost(message, repeated, tag = "7")]
        pub vtx: Vec<CompactTx>,
    }

    /// Compact transaction within a CompactBlock.
    #[derive(Clone, PartialEq, Message)]
    pub struct CompactTx {
        #[prost(uint64, tag = "1")]
        pub index: u64,
        #[prost(bytes, tag = "2")]
        pub hash: Vec<u8>,
        #[prost(uint32, tag = "3")]
        pub fee: u32,
        /// Sapling spends. Orchard actions are field 6 and Ironwood actions
        /// are field 9 in current lightwalletd responses.
        #[prost(bytes = "vec", repeated, tag = "4")]
        pub sapling_spends: Vec<Vec<u8>>,
        #[prost(message, repeated, tag = "6")]
        pub orchard_actions: Vec<CompactOrchardAction>,
        #[prost(message, repeated, tag = "9")]
        pub ironwood_actions: Vec<CompactOrchardAction>,
    }

    /// Compact Orchard action for trial decryption.
    #[derive(Clone, PartialEq, Message)]
    pub struct CompactOrchardAction {
        #[prost(bytes, tag = "1")]
        pub nullifier: Vec<u8>,
        #[prost(bytes, tag = "2")]
        pub cmx: Vec<u8>,
        #[prost(bytes, tag = "3")]
        pub ephemeral_key: Vec<u8>,
        #[prost(bytes, tag = "4")]
        pub ciphertext: Vec<u8>,
    }

    /// Raw transaction response from GetTransaction.
    #[derive(Clone, PartialEq, Message)]
    pub struct RawTransaction {
        #[prost(bytes, tag = "1")]
        pub data: Vec<u8>,
        #[prost(uint64, tag = "2")]
        pub height: u64,
    }

    /// TxFilter for GetTransaction.
    #[derive(Clone, PartialEq, Message)]
    pub struct TxFilter {
        #[prost(message, optional, tag = "1")]
        pub block: Option<BlockId>,
        #[prost(bytes, tag = "2")]
        pub index: Vec<u8>,
        #[prost(bytes, tag = "3")]
        pub hash: Vec<u8>,
    }
}

// ---------------------------------------------------------------------------
// LightwalletdClient
// ---------------------------------------------------------------------------

/// A tonic gRPC client wrapper for lightwalletd.
/// One instance per configured network profile.
#[derive(Clone)]
pub struct LightwalletdClient {
    channel: Channel,
    limits: LimitsConfig,
}

impl LightwalletdClient {
    /// Connects to the lightwalletd endpoint with optional TLS.
    ///
    /// Connection is lazy — the channel is not opened until the first RPC call.
    pub async fn connect(url: &str, limits: &LimitsConfig) -> Result<Self, RelayError> {
        let endpoint = tonic::transport::Endpoint::from_shared(url.to_owned())
            .map_err(|e| RelayError::Configuration(format!("Invalid upstream URL: {e}")))?
            .timeout(Duration::from_secs(limits.upstream_timeout_secs))
            .tcp_keepalive(Some(Duration::from_secs(30)));

        // Apply TLS if the URL uses https / grpcs scheme.
        let endpoint = if url.starts_with("https://") || url.starts_with("grpcs://") {
            let tls = ClientTlsConfig::new()
                .with_native_roots();
            endpoint.tls_config(tls).map_err(|e| {
                RelayError::Configuration(format!("TLS configuration failed: {e}"))
            })?
        } else {
            endpoint
        };

        let channel = endpoint.connect_lazy();

        Ok(Self {
            channel,
            limits: limits.clone(),
        })
    }

    /// Fetches the latest block height from the upstream.
    pub async fn get_latest_height(&self) -> Result<u64, RelayError> {
        use proto::BlockId;

        let request = tonic::Request::new(proto::BlockId {
            height: 0,
            hash: vec![],
        });

        let response = timeout(
            Duration::from_secs(self.limits.upstream_timeout_secs),
            self.call_get_latest_block(request),
        )
        .await
        .map_err(|_| RelayError::UpstreamUnavailable {
            reason: "Timed out waiting for latest block height.".into(),
        })?
        .map_err(RelayError::from)?;

        Ok(response.into_inner().height)
    }

    /// Fetches compact blocks in the range `[start_height, end_height]`.
    ///
    /// Returns the raw protobuf-serialised bytes of each block concatenated
    /// in a length-delimited frame format suitable for browser decoding.
    ///
    /// Response size is checked against `limits.max_response_bytes` before
    /// being returned to prevent oversized allocations.
    pub async fn get_block_range(
        &self,
        start_height: u32,
        end_height: u32,
    ) -> Result<Vec<u8>, RelayError> {
        use proto::{BlockId, BlockRange};
        use prost::Message;

        let request = tonic::Request::new(BlockRange {
            start: Some(BlockId {
                height: start_height as u64,
                hash: vec![],
            }),
            end: Some(BlockId {
                height: end_height as u64,
                hash: vec![],
            }),
        });

        let mut stream = timeout(
            Duration::from_secs(self.limits.upstream_timeout_secs),
            self.call_get_block_range(request),
        )
        .await
        .map_err(|_| RelayError::UpstreamUnavailable {
            reason: "Timed out waiting for block range stream.".into(),
        })?
        .map_err(RelayError::from)?
        .into_inner();

        // Collect streaming compact blocks into a length-delimited buffer.
        let mut out: Vec<u8> = Vec::new();
        while let Some(block) = stream.message().await.map_err(RelayError::from)? {
            let block_bytes = block.encode_to_vec();
            // Length prefix (4 bytes, big-endian).
            let len = block_bytes.len() as u32;
            out.extend_from_slice(&len.to_be_bytes());
            out.extend_from_slice(&block_bytes);

            // Reject oversized responses mid-stream.
            validate_response_size(out.len(), &self.limits)?;
        }

        Ok(out)
    }

    /// Fetches a full raw transaction by its hex-encoded ID.
    ///
    /// Privacy: The txid must have been validated to be a 64-char hex string
    /// before this is called. The txid is NOT logged by this function; the
    /// caller (`routes/transaction.rs`) handles privacy-redacted logging.
    pub async fn get_transaction(&self, txid_hex: &str) -> Result<Vec<u8>, RelayError> {
        use proto::TxFilter;
        use prost::Message;

        // Decode the hex txid into 32 bytes.
        let hash_bytes = hex::decode(txid_hex).map_err(|_| {
            RelayError::InvalidTxId("Failed to hex-decode transaction ID.".into())
        })?;

        let request = tonic::Request::new(TxFilter {
            block: None,
            index: vec![],
            hash: hash_bytes,
        });

        let response = timeout(
            Duration::from_secs(self.limits.upstream_timeout_secs),
            self.call_get_transaction(request),
        )
        .await
        .map_err(|_| RelayError::UpstreamUnavailable {
            reason: "Timed out waiting for transaction data.".into(),
        })?
        .map_err(RelayError::from)?;

        let raw_tx = response.into_inner();
        validate_response_size(raw_tx.data.len(), &self.limits)?;
        Ok(raw_tx.data)
    }

    // ---- Live gRPC calls via tonic::client::Grpc to lightwalletd CompactTxStreamer ----

    /// Calls `GetLatestBlock` on upstream lightwalletd.
    async fn call_get_latest_block(
        &self,
        request: tonic::Request<proto::BlockId>,
    ) -> Result<tonic::Response<proto::BlockId>, tonic::Status> {
        let mut grpc = tonic::client::Grpc::new(self.channel.clone());
        let codec = tonic::codec::ProstCodec::default();
        let path = http::uri::PathAndQuery::from_static(
            "/cash.z.wallet.sdk.rpc.CompactTxStreamer/GetLatestBlock",
        );
        grpc.ready()
            .await
            .map_err(|e| tonic::Status::unavailable(e.to_string()))?;
        grpc.unary(request, path, codec).await
    }

    /// Calls `GetBlockRange` on upstream lightwalletd, streaming compact blocks.
    async fn call_get_block_range(
        &self,
        request: tonic::Request<proto::BlockRange>,
    ) -> Result<tonic::Response<tonic::codec::Streaming<proto::CompactBlock>>, tonic::Status> {
        let mut grpc = tonic::client::Grpc::new(self.channel.clone());
        let codec = tonic::codec::ProstCodec::default();
        let path = http::uri::PathAndQuery::from_static(
            "/cash.z.wallet.sdk.rpc.CompactTxStreamer/GetBlockRange",
        );
        grpc.ready()
            .await
            .map_err(|e| tonic::Status::unavailable(e.to_string()))?;
        grpc.server_streaming(request, path, codec).await
    }

    /// Calls `GetTransaction` on upstream lightwalletd.
    async fn call_get_transaction(
        &self,
        request: tonic::Request<proto::TxFilter>,
    ) -> Result<tonic::Response<proto::RawTransaction>, tonic::Status> {
        let mut grpc = tonic::client::Grpc::new(self.channel.clone());
        let codec = tonic::codec::ProstCodec::default();
        let path = http::uri::PathAndQuery::from_static(
            "/cash.z.wallet.sdk.rpc.CompactTxStreamer/GetTransaction",
        );
        grpc.ready()
            .await
            .map_err(|e| tonic::Status::unavailable(e.to_string()))?;
        grpc.unary(request, path, codec).await
    }
}

#[cfg(test)]
mod proto_tests {
    use super::proto::CompactTx;
    use prost::Message;

    fn bytes_field(tag: u8, payload: &[u8]) -> Vec<u8> {
        let mut encoded = vec![(tag << 3) | 2];
        let mut len = payload.len() as u64;
        while len >= 0x80 {
            encoded.push((len as u8) | 0x80);
            len >>= 7;
        }
        encoded.push(len as u8);
        encoded.extend_from_slice(payload);
        encoded
    }

    #[test]
    fn preserves_sapling_and_current_orchard_ironwood_fields() {
        let mut action = Vec::new();
        for tag in 1..=4 {
            let size = if tag == 4 { 52 } else { 32 };
            action.extend(bytes_field(tag, &vec![tag; size]));
        }

        let mut compact_tx = Vec::new();
        compact_tx.extend(bytes_field(4, &action));
        compact_tx.extend(bytes_field(6, &action));
        compact_tx.extend(bytes_field(9, &action));

        let decoded = CompactTx::decode(compact_tx.as_slice())
            .expect("compact transaction fields should decode");
        assert_eq!(decoded.sapling_spends.len(), 1);
        assert_eq!(decoded.orchard_actions.len(), 1);
        assert_eq!(decoded.ironwood_actions.len(), 1);

        let roundtrip = CompactTx::decode(decoded.encode_to_vec().as_slice())
            .expect("compact transaction fields should round-trip");
        assert_eq!(roundtrip, decoded);
    }
}
